# Creating a list
nums = [10, 20, 30, 40, 50]

# Indexing
print("First element:", nums[0])
print("Last element:", nums[-1])

# Slicing
print("Elements from index 1 to 3:", nums[1:4])
print("First three elements:", nums[:3])
print("Every second element:", nums[::2])
print("Reversed list:", nums[::-1])

# Mixed data types
mixed = [1, "hello", True, 3.14]
print("Mixed list:", mixed)

# Nested list
nested = [[1, 2], [3, 4], [5, 6]]

# Accessing nested list element
print("Element at nested[1][0]:", nested[1][0])