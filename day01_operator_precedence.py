# Day 1 - Operator Precedence & Associativity

print("Operator Precedence and Associativity\n")

value1 = 2 + 3 * 4
print("2 + 3 * 4 =", value1)

value2 = 10 - 6 / 2
print("10 - 6 / 2 =", value2)

value3 = (2 + 3) * 4
print("(2 + 3) * 4 =", value3)        

value4 = 20 / 5 * 2
print("20 / 5 * 2 =", value4)

value5 = 2 ** 3 ** 2
print("2 ** 3 ** 2 =", value5)